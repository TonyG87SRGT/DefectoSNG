import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const rootDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const read = relative => JSON.parse(fs.readFileSync(path.join(rootDir, relative), "utf8"));
const write = (relative, value) => fs.writeFileSync(path.join(rootDir, relative), `${JSON.stringify(value, null, 2)}\n`);

function ensureDir(relative) {
  fs.mkdirSync(path.join(rootDir, relative), { recursive: true });
}

function writeAsset(relative, content) {
  const absolute = path.join(rootDir, relative);
  fs.mkdirSync(path.dirname(absolute), { recursive: true });
  fs.writeFileSync(absolute, content);
}

