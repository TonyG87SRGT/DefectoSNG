function waveform(points) {
  const baseline = 190;
  let d = `M 42 ${baseline}`;
  for (const [x, height] of points) {
    d += ` L ${x - 10} ${baseline} L ${x} ${baseline - height} L ${x + 10} ${baseline}`;
  }
  return `${d} L 758 ${baseline}`;
}

