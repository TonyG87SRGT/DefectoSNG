import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const dataPath = path.join(root, "data", "rk.json");
const items = JSON.parse(fs.readFileSync(dataPath, "utf8"));
const byId = new Map(items.map(item => [item.id, item]));

const related = (...ids) => ({
  type: "related",
  title: "Связанные материалы",
  items: ids.map(id => {
    const target = byId.get(id);
    if (!target) throw new Error(`Related article not found: ${id}`);
    return { method: "rk", id, title: target.title };
  })
});

function article(id, parentId, order, title, summary, tags, sections) {
  return {
    id,
    type: "article",
    parentId,
    order,
    status: "published",
    category: byId.get(parentId)?.title.toUpperCase() || "РАДИОГРАФИЧЕСКИЙ КОНТРОЛЬ",
    title,
    summary,
    tags,
    sections
  };
}

