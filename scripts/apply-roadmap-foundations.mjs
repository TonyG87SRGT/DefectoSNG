import fs from "node:fs";

const vibrationPath = "data/vibration.json";
const vibration = JSON.parse(fs.readFileSync(vibrationPath, "utf8"));
const removedIds = new Set([
  "vibration-tool-diagnostic-tree",
  "vibration-reference-bearing-frequencies",
  "vibration-reference-pump-frequencies",
  "vibration-reference-fan-frequencies",
  "vibration-reference-gearbox-frequencies",
  "vibration-reference-directions",
  "vibration-reference-diagnostic-signs",
  "vibration-reference-fault-sign-check",
  "vibration-reference-terms",
  "vibration-reference-units",
  "vibration-reference-abbreviations"
]);

const cleaned = vibration
  .filter(item => !removedIds.has(item.id))
  .map(item => {
    if (item.id === "vibration-reference") {
      return {
        ...item,
        summary: "Четыре взаимодополняющих материала: термины и сокращения, единицы, характерные частоты и нормативные документы — без повторения профильных статей."
      };
    }
    if (item.parentId === "vibration-tools" && item.toolConfig) {
      return {
        ...item,
        toolConfig: { ...item.toolConfig, scope: "method" }
      };
    }
    return item;
  });

fs.writeFileSync(vibrationPath, `${JSON.stringify(cleaned, null, 2)}\n`);

